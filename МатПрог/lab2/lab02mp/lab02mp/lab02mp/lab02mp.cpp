// Исследование временной зависимости (Задание 6) // Комментарий: ниже функция исследования времени работы.
void investigateTimeDependency() {            // Объявляем функцию исследования зависимости времени от числа городов.
    cout << "ЗАДАНИЕ 6: Исследование зависимости времени от количества городов\n"; // Печатаем заголовок шестого задания.
    cout << "Количество городов | Время (мс)\n"; // Печатаем заголовок таблицы результатов.
    cout << "-------------------|-----------\n"; // Печатаем разделительную линию таблицы.

    int* d6 = new int[MAX_CITIES * MAX_CITIES]; // Выделяем память под матрицу максимального размера.
    int* r6 = new int[MAX_CITIES];            // Выделяем память под маршрут максимального размера.

    for (int cities = 6; cities <= MAX_CITIES; cities++) { // Перебираем количество городов от 6 до MAX_CITIES.
        for (int i = 0; i < cities; i++) {    // Проходим по строкам текущей матрицы.
            for (int j = 0; j < cities; j++) { // Проходим по столбцам текущей матрицы.
                if (i == j)                   // Если это расстояние до самого себя,
                    d6[i * cities + j] = 0;   // записываем 0.
                else                          // Иначе
                    d6[i * cities + j] = auxil::iget(10, 300); // записываем случайное расстояние.
            }                                 // Конец внутреннего цикла заполнения матрицы.
        }                                     // Конец внешнего цикла заполнения матрицы.

        for (int k = 0; k < 2; k++) {         // Два раза добавляем бесконечные переходы.
            int i, j;                         // Объявляем переменные для индексов городов.
            do {                              // Начинаем подбор разных городов.
                i = auxil::iget(0, cities - 1); // Выбираем случайный первый город.
                j = auxil::iget(0, cities - 1); // Выбираем случайный второй город.
            } while (i == j);                 // Повторяем, пока города не станут разными.
            d6[i * cities + j] = INF;         // Делаем путь из i в j бесконечным.
            d6[j * cities + i] = INF;         // Делаем обратный путь тоже бесконечным.
        }                                     // Конец цикла добавления бесконечных переходов.

        clock_t t_start = clock();            // Замеряем время начала решения задачи.
        salesman(cities, d6, r6);             // Решаем задачу коммивояжёра для текущего числа городов.
        clock_t t_end = clock();              // Замеряем время окончания решения.

        cout << setw(17) << cities << " | " << setw(9) << (t_end - t_start) << "\n"; // Выводим число городов и время работы.
    }                                         // Конец цикла по количеству городов.

    delete[] d6;                              // Освобождаем память матрицы расстояний.
    delete[] r6;                              // Освобождаем память маршрута.
}                                             // Конец функции investigateTimeDependency().

