// Функция для генерации матрицы расстояний (Задание 5) // Комментарий: ниже функция заполнения матрицы расстояний.
void generateDistanceMatrix(int* d, int n, int infCount) { // Объявляем функцию генерации матрицы расстояний.
    for (int i = 0; i < n; i++) {             // Проходим по всем строкам матрицы.
        for (int j = 0; j < n; j++) {         // Проходим по всем столбцам матрицы.
            if (i == j)                       // Если рассматриваем расстояние города до самого себя,
                d[i * n + j] = 0;             // то записываем 0.
            else                              // Иначе, если это разные города,
                d[i * n + j] = auxil::iget(10, 300); // задаём случайное расстояние от 10 до 300.
        }                                     // Конец внутреннего цикла по столбцам.
    }                                         // Конец внешнего цикла по строкам.

    for (int k = 0; k < infCount; k++) {      // Несколько раз добавляем недоступные пути с бесконечной длиной.
        int i, j;                             // Объявляем переменные для случайной пары городов.
        do {                                  // Начинаем цикл подбора корректной пары.
            i = auxil::iget(0, n - 1);        // Случайно выбираем первый город.
            j = auxil::iget(0, n - 1);        // Случайно выбираем второй город.
        } while (i == j);                     // Повторяем, пока не выбраны два разных города.

        d[i * n + j] = INF;                   // Делаем путь из i в j бесконечным.
        d[j * n + i] = INF;                   // Делаем обратный путь тоже бесконечным.
    }                                         // Конец цикла добавления бесконечных расстояний.
}                                             // Конец функции generateDistanceMatrix().

